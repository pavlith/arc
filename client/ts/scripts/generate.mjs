import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = new URL('../../../', import.meta.url);
const checking = process.argv.includes('--check');
const pascal = (s) => s.split(/[_.-]/).map((v) => v[0].toUpperCase() + v.slice(1)).join('');
const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
function type(s) {
  if (s === true) return 'unknown';
  if (s === false) return 'never';
  if (Object.hasOwn(s, 'const')) return JSON.stringify(s.const);
  if (s.anyOf) return s.anyOf.map(type).join(' | ');
  if (s.$ref || s.allOf) throw new Error('Unsupported schema composition');
  if (s.oneOf) return s.oneOf.map((branch) => {
    if (Object.keys(branch).some((key) => !['required', 'not'].includes(key))) throw new Error('Unsupported oneOf branch');
    const exclusions = branch.not?.anyOf ?? (branch.not ? [branch.not] : []);
    if (branch.not?.anyOf && Object.keys(branch.not).some((key) => key !== 'anyOf')) throw new Error('Unsupported exclusion');
    for (const exclusion of exclusions) {
      if (Object.keys(exclusion).some((key) => key !== 'required') || exclusion.required?.length !== 1) throw new Error('Unsupported exclusion combination');
    }
    const properties = { ...s.properties };
    for (const exclusion of exclusions) properties[exclusion.required[0]] = false;
    return type({ ...s, oneOf: undefined, properties, required: [...(s.required ?? []), ...(branch.required ?? [])] });
  }).join(' | ');
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (Array.isArray(s.type)) return s.type.map((t) => type({ ...s, type: t })).join(' | ');
  switch (s.type) {
    case 'null': return 'null';
    case 'boolean': return 'boolean';
    case 'integer': case 'number': return 'number';
    case 'string': return 'string';
    case 'array': return `Array<${type(s.items ?? true)}>`;
    case 'object': {
      const properties = Object.entries(s.properties ?? {}).map(([k, v]) => `${JSON.stringify(k)}${s.required?.includes(k) ? '' : '?'}: ${type(v)}`);
      if (s.additionalProperties !== false) properties.push(`[key: string]: ${type(s.additionalProperties ?? true)}`);
      return properties.length ? `{ ${properties.join('; ')} }` : 'Record<string, never>';
    }
    default: throw new Error(`Unsupported schema type ${s.type}`);
  }
}
function treeCode(tree, indent = '  ') {
  const entries = Object.entries(tree).filter(([key]) => key !== '__call');
  const object = '{\n' + entries.map(([key, value]) => `${indent}${JSON.stringify(key)}: ${typeof value === 'string' ? value : treeCode(value, indent + '  ')}`).join(',\n') + '\n' + indent.slice(2) + '}';
  return tree.__call ? (entries.length ? `Object.assign(${tree.__call}, ${object})` : tree.__call) : object;
}
for (const service of ['task', 'notify', 'files', 'pages']) {
  const dir = new URL(`services/${service}/api/v1/contract/`, root);
  const manifestRaw = readFileSync(new URL('manifest.json', dir));
  const manifest = JSON.parse(manifestRaw);
  const hash = createHash('sha256').update(manifestRaw);
  const aliases = new Map();
  const alias = (path) => {
    if (!aliases.has(path)) {
      const raw = readFileSync(new URL(path, dir)); hash.update(path).update(raw);
      aliases.set(path, { name: pascal(service + '_' + path.split('/').pop().replace('.json', '')), schema: JSON.parse(raw) });
    }
    return aliases.get(path).name;
  };
  const tree = {};
  for (const op of manifest.operations.filter((op) => op.http?.expose)) {
    const request = alias(op.request_schema), response = alias(op.response_schema);
    const command = op.kind === 'command';
    const route = JSON.stringify({ method: op.http.method, path: op.http.path, bindings: op.http.bindings ?? [] });
    const parts = op.id.split('.').slice(1).map(camel);
    let branch = tree;
    for (const part of parts.slice(0, -1)) {
      branch = branch[part] ??= {};
    }
    const key = parts.at(-1);
    branch[key] ??= {};
    if (branch[key].__call) throw new Error('Operation collision');
    branch[key].__call = `(input: ${request}, options${command ? '' : '?'}: ${command ? 'CommandOptions' : 'CallOptions'}) => callRoute<${request}, ${response}>(transport, ${route}, input, options)`;
  }
  const name = pascal(service);
  const content = `// Generated by scripts/generate.mjs. Do not edit.\n// ${service} ${manifest.service.build_version}; input fingerprint ${hash.digest('hex')}\nimport { callRoute, type Transport, type CallOptions, type CommandOptions } from './transport.js';\n\n` + [...aliases.values()].map(({ name, schema }) => `export type ${name} = ${type(schema)};`).join('\n\n') + `\n\nexport function create${name}API(transport: Transport) {\n  return ${treeCode(tree)};\n}\n`;
  const target = new URL(`../src/${service}.generated.ts`, import.meta.url);
  if (checking) {
    if (readFileSync(target, 'utf8') !== content) throw new Error(`Stale generated client: ${fileURLToPath(target)}`);
  } else writeFileSync(target, content);
}
console.log(checking ? 'Client contracts are current.' : 'Client contracts generated.');
